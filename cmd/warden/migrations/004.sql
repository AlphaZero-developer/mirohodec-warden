CREATE TABLE IF NOT EXISTS managed_chats (
			chat_id BIGINT PRIMARY KEY,
			title TEXT NOT NULL DEFAULT '',
			enabled BOOLEAN NOT NULL DEFAULT TRUE,
			rehab_topic_id INTEGER NOT NULL DEFAULT 0,
			spam_no_rehab_action TEXT NOT NULL DEFAULT 'mute_on_delete',
			debug_commands BOOLEAN NOT NULL DEFAULT FALSE,
			updated_unix BIGINT NOT NULL DEFAULT 0,
			ai_enabled_mode TEXT NOT NULL DEFAULT '',
			spam_enabled_mode TEXT NOT NULL DEFAULT '',
			warn_enabled_mode TEXT NOT NULL DEFAULT '',
			karma_enabled_mode TEXT NOT NULL DEFAULT '',
			faq_enabled_mode TEXT NOT NULL DEFAULT '',
			quotes_enabled_mode TEXT NOT NULL DEFAULT '',
			photos_enabled_mode TEXT NOT NULL DEFAULT '',
			warn_expire_after TEXT NOT NULL DEFAULT '',
			warn_mute_threshold INTEGER NOT NULL DEFAULT 0,
			warn_mute_duration TEXT NOT NULL DEFAULT '',
			warn_rehab_threshold INTEGER NOT NULL DEFAULT 0,
			warn_rehab_duration TEXT NOT NULL DEFAULT '',
			karma_messages_per_point INTEGER NOT NULL DEFAULT 0,
			karma_daily_limit INTEGER NOT NULL DEFAULT 0,
			karma_manual_cooldown TEXT NOT NULL DEFAULT ''
		)
