CREATE TABLE IF NOT EXISTS members (
			chat_id BIGINT NOT NULL,
			user_id BIGINT NOT NULL,
			username TEXT NOT NULL DEFAULT '',
			first_name TEXT NOT NULL DEFAULT '',
			last_name TEXT NOT NULL DEFAULT '',
			display_name TEXT NOT NULL DEFAULT '',
			is_bot BOOLEAN NOT NULL DEFAULT FALSE,
			first_seen BIGINT NOT NULL DEFAULT 0,
			last_seen BIGINT NOT NULL DEFAULT 0,
			last_message BIGINT NOT NULL DEFAULT 0,
			last_message_id INTEGER NOT NULL DEFAULT 0,
			last_thread_id INTEGER NOT NULL DEFAULT 0,
			messages BIGINT NOT NULL DEFAULT 0,
			messages_today BIGINT NOT NULL DEFAULT 0,
			activity_day TEXT NOT NULL DEFAULT '',
			last_rehab_duration BIGINT NOT NULL DEFAULT 0,
			rehab_escape_penalty INTEGER NOT NULL DEFAULT 0,
			achievements TEXT[] NOT NULL DEFAULT '{}',
			shop_title TEXT NOT NULL DEFAULT '',
			shop_title_until BIGINT NOT NULL DEFAULT 0,
			laya_tone TEXT NOT NULL DEFAULT '',
			laya_charm_until BIGINT NOT NULL DEFAULT 0,
			quote_boost_until BIGINT NOT NULL DEFAULT 0,
			PRIMARY KEY (chat_id, user_id)
		)
